/**
 * 1. โครงสร้างผลกระทบของการเลือกตัวเลือก (Choice Effects Schema)
 */
export interface ExternalEventEffects {
  corpseMeals?: number;
  endured?: number;
  hp?: number;               // สภาพร่างกาย (-100 ถึง +100)
  hunger?: number;           // ความหิว (-100 คืออิ่มขึ้น, +100 คือหิวขึ้น)
  sanity?: number;           // สติสัมปชัญญะ (-100 ถึง +100)
  humanity?: number;         // ความเป็นมนุษย์/ความเห็นใจ (-100 ถึง +100)
  mutation?: number;         // การกลายพันธุ์ (-100 ถึง +100)
  research?: number;         // ความเข้าใจเชื้อ/งานวิจัย (-100 ถึง +100)
  horde?: number;            // อำนาจสั่งการฝูง (-100 ถึง +100)
  supplies?: number;         // เสบียงอาหารกระป๋องของมนุษย์ (จำนวนชิ้น)
  medicine?: number;         // ชุดเย็บแผล/เวชภัณฑ์ (จำนวนชิ้น)
  samples?: number;          // หลอดตัวอย่างเชื้อ (จำนวนชิ้น)
  carriedBloodBags?: number; // ถุงเลือดสำรองพกพา (จำนวนถุง)
  targetNpcTrustDelta?: number; // ความไว้ใจของ NPC เป้าหมาย (-100 ถึง +100)
  bystanderTrustDelta?: number; // ความไว้ใจของ NPC ทุกคนในเขตนั้น (-100 ถึง +100)
  killTargetNpc?: boolean;   // สังหาร NPC เป้าหมายหรือไม่ (ถ้า true จะเพิ่ม Kill Count +1 และลดประชากรเขต)
  resolveNpcCrisis?: boolean;// แก้วิกฤตของ NPC สำเร็จหรือไม่
  threatDelta?: number;      // ระดับภัยคุกคามของเขต (-50 ถึง +50)
  setFlag?: string;          // ตั้งค่า Flag เนื้อเรื่องเพื่อไปทริกเกอร์เหตุการณ์ต่อเนื่องหรือฉากจบ
  setFlags?: string[];       // ตั้งค่าหลาย Flag พร้อมกัน
  triggerEndingId?:          // หากตัวเลือกนี้นำไปสู่ฉากจบโดยตรง (ใช้เฉพาะใน Climax Trigger Event)
    | 'human'
    | 'king'
    | 'evolved'
    | 'extinction'
    | 'silent_guardian'
    | 'escape_companion'
    | 'horde_breakout'
    | 'conscious_exile'
    | 'death'
    | 'feral';
}

/**
 * 2. โครงสร้างเหตุการณ์สำรวจ / เหตุการณ์ประจำวัน / เหตุการณ์ทริกเกอร์ฉากจบ
 */
export interface ExternalGameEventTemplate {
  id: string;
  category?: 'roam' | 'timeline' | 'npc_encounter' | 'ending_climax';
  placeId?: BangkokZoneId | 'any';
  title: string;
  text: string;
  dayNote: string;
  advanceDay?: boolean;
  /** เงื่อนไขการเกิดเหตุการณ์ (Trigger Conditions) */
  conditions?: {
    places?: BangkokZoneId[];       // เขตที่เกิดได้ (ถ้าไม่ระบุคือดูจาก placeId หรือเกิดได้ทุกเขต)
    minDay?: number;                // วันที่ขั้นต่ำ (1 - 120)
    maxDay?: number;                // วันที่สูงสุด (1 - 120)
    exactDay?: number;              // เกิดเฉพาะวันที่ระบุ (สำหรับ category: 'timeline')
    minSanity?: number;
    minHumanity?: number;
    maxHumanity?: number;
    minMutation?: number;
    minResearch?: number;
    minHorde?: number;
    minCampaign?: number;
    minTrust?: number;              // ความไว้ใจรวมขั้นต่ำ (0 - 100)
    minZoneTrust?: number;          // ความไว้ใจเฉลี่ยของเขตขั้นต่ำ (0 - 100)
    minZoneAverageTrust?: number;   // Alias สำหรับความไว้ใจเฉลี่ยของเขตขั้นต่ำ
    requiresMaxTrustCompanion?: boolean; // ต้องมี NPC ที่ไว้ใจ 100/100 หรือไม่
    requiresMaxTrustNpcInZone?: boolean; // Alias สำหรับ NPC ที่ไว้ใจ 100/100
    minSavedCount?: number;         // จำนวนครั้งที่ช่วยคนขั้นต่ำ
    maxKilledCount?: number;        // จำนวนศพที่ฆ่าไม่เกินกี่ศพ (เช่น 0 สำหรับสายไม่ฆ่าคน)
    maxKillCount?: number;          // Alias สำหรับจำนวนศพที่ฆ่าไม่เกินกี่ศพ
    minSamples?: number;            // จำนวนหลอดตัวอย่างเชื้อขั้นต่ำ
    requiredFlag?: string;          // ต้องมี Flag นี้มาก่อน
    forbiddenFlag?: string;         // ห้ามมี Flag นี้ (เช่น ค้นจนหมดแล้ว)
    oncePerRun?: boolean;           // เกิดได้แค่ครั้งเดียวต่อการเล่น 1 รอบหรือไม่
    cooldownDays?: number;          // จำนวนวันคูลดาวน์ก่อนจะมีสิทธิ์สุ่มพบได้อีก
  };
  choices: Array<{
    text: string;
    note: string;
    outcomeText: string;
    partKey?: string;               // รหัสชิ้นส่วนสำหรับเหตุการณ์จำกัดส่วน (เช่น roam-streets-wreck-pile)
    /** เงื่อนไขในการเปิดให้กดตัวเลือกนี้ (ถ้าไม่ระบุคือเปิดให้กดเสมอ) */
    choiceRequirements?: {
      minMutationStage?: 1 | 2 | 3 | 4;
      requiresSupplies?: number;
      requiresMedicine?: number;
      requiresSamples?: number;
      requiresCarriedBloodBags?: number;
      requiresSignatureItem?: boolean;
    };
    effects: ExternalEventEffects;
  }>;
}

