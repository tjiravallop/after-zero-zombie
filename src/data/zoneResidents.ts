export function materializeZoneResidents(zone: ZonePopulationState, seed: number) {
  const place = zone.placeId === 'tower' ? 'radio' : zone.placeId;
  const localRoles = roles[place] ?? [['ผู้รอดชีวิตในย่าน', 'คอยตรวจทางออกและเก็บของจำเป็นไว้ใกล้มือ']];
  const usedNames = new Set(zone.npcs.map(npc => npc.name));
  const ids = new Set(zone.npcs.map(npc => npc.id));
  const offset = (seed + [...place].reduce((hash, char) => Math.imul(hash, 31) + char.charCodeAt(0), 0)) >>> 0;
  const count = Math.min(zone.unmetAnonymousSurvivors, 100 - zone.npcs.length);
  for (let slot = 0, added = 0; slot < names.length && added < count; slot++) {
    const id = `npc-resident-${place}-${slot}`;
    const name = names[(offset + slot) % names.length];
    if (ids.has(id) || usedNames.has(name)) continue;
    const [role, trait] = localRoles[(offset + added) % localRoles.length];
    zone.npcs.push({
      id, name, role, trait, placeId: place,
      age: 19 + (offset + slot * 17) % 46,
      alive: true, met: false, trust: 0, localResident: true,
      lastNote: 'ยังไม่เคยเผชิญหน้าโดยตรง',
    });
    zone.unmetAnonymousSurvivors--;
    added++;
  }
}
